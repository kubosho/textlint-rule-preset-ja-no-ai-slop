import { createRule, find } from "../rule.js";

const reason = "別分野の用語をソフトウェア開発の説明に流用すると、読み手にその分野での意味を考えさせます。";
const context = "文脈によっては本来の分野の意味など問題ない場合もあります。何を指す言葉か、実際の対象と動作を確かめてください。";

const terms = [
  [/過積載/g, "何が余分なのか、その要素を具体的に書いてください。"],
  [/越権/g, "どの作業がどの担当範囲から外れるのかを書いてください。"],
  [/正本/g, "「唯一の参照元」「基準となる記述」のように役割を書いてください。"],
  [/憲法/g, "優先順位を指すなら「最優先のルール」と書いてください。"],
  [/未決(?!定|済|着|算|裁)/g, "「未確定」「まだ決めていない」のように状態を書いてください。"],
  [/布告/g, "誰がどの方針を誰に知らせたかを書いてください。"],
  [/追い返(?:し(?:た|て|ます|ました)?|す|さ(?:ない|れ(?:る|た|て))|せば|そう)/g, "相手に何を返すのか、質問や差し戻す理由を具体的に書いてください。"],
  [/(?<![\p{Script=Han}々\p{Script=Katakana}ー0-9０-９A-Za-zＡ-Ｚａ-ｚ])語(?:(?=自体|単位|同士)|(?![\p{Script=Han}々らりるれろっ]))/gu, "数えられる単位なら「単語」、一般には「言葉」、句を含むなら「表現」、文章中の位置なら「箇所」のように、指す対象に合わせて書いてください。"],
];

export default createRule((sentences) =>
  terms.flatMap(([pattern, correction]) => find(sentences, pattern, `${reason}${correction}${context}`)),
);
