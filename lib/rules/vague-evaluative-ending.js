import { createRule, find } from "../rule.js";

const message = "汎用的な評価語で閉じており、何がどう変わったかが文章から読み取れません。変更したこと、変化した対象、観察された結果を書いてください。変化した対象と観察された結果を確認してください。";

export default createRule((sentences) => [
  ...find(sentences, /(?:効(?:く|きます|きました|いた|いている|いています|いていた|いていました)|刺さ(?:る|ります|りました|った|っている|っています)|響(?:く|きます|きました|いた|いている|いています)|効果的(?:だ|です|だった|でした))(?=(?:ね|よ)?[。！？!?]*\s*$)/g, message),
  ...find(sentences, /(?:効く|効いた|効いている|刺さる|刺さった|響く|響いた)の(?:が|は)/g, message),
]);
